def rows(path):
    """The fields of every data line."""
    for line in path.read_text(encoding="utf-8").splitlines():
        data = line.split("#", 1)[0].strip()
        if data:
            yield [field.strip() for field in data.split(";")]


def points(field):
    return [int(point, 16) for point in field.split()]


def check_version(path, name):
    """The file is `name` of Unicode VERSION, by its own header."""
    header = path.read_text(encoding="utf-8").splitlines()[:12]
    major_minor = VERSION.rsplit(".", 1)[0]
    if header[:1] != [f"# {name}-{VERSION}.txt"] and not (
            header[:1] == [f"# {name}.txt"] and f"# Version: {major_minor}" in header):
        sys.exit(f"{path}: not {name} of Unicode {VERSION}")


def main(argv):
    if len(argv) != 4:
        sys.exit(__doc__)
    standardized, emoji_variation, emoji_sequences = (Path(arg) for arg in argv[1:])
    check_version(standardized, "StandardizedVariants")
    check_version(emoji_variation, "emoji-variation-sequences")
    check_version(emoji_sequences, "emoji-sequences")

    pairs = set()
    for path in (standardized, emoji_variation):
        for fields in rows(path):
            pair = points(fields[0])
            if len(pair) != 2:
                sys.exit(f"{path}: not a pair: {fields[0]}")
            pairs.add(tuple(pair))
    tags = sorted(tuple(points(fields[0])) for fields in rows(emoji_sequences)
                  if fields[1:2] == ["RGI_Emoji_Tag_Sequence"])
    if not pairs or not tags:
        sys.exit("no sequences found")

    out = ["// Generated by scripts/generate_identity_sequences.py; do not edit.", "//"]
    out.append(f"// From the Unicode Character Database {VERSION}:")
    for path in (standardized, emoji_variation, emoji_sequences):
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        out.append(f"//   {path.name} (sha256 {digest})")
    out.append("//")
    out.extend(f"// {line}".rstrip() for line in NOTICE.splitlines())
    out.append("")
    out.append("/// Every registered variation sequence, as (base, selector), sorted:")
    out.append("/// StandardizedVariants.txt and emoji-variation-sequences.txt.")
    out.append("pub(crate) const VARIATION_SEQUENCES: &[(u32, u32)] = &[")
    out.extend(f"    (0x{base:04X}, 0x{selector:04X})," for base, selector in sorted(pairs))
    out.append("];")
    out.append("")
    out.append("/// The RGI emoji tag sequences of emoji-sequences.txt, sorted.")
    out.append("pub(crate) const TAG_SEQUENCES: &[&[u32]] = &[")
    for sequence in tags:
        # As rustfmt lays out an array too long for one line.
        out.append("    &[")
        out.append("        " + ", ".join(f"0x{point:04X}" for point in sequence) + ",")
        out.append("    ],")
    out.append("];")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv)
